#!/bin/bash
set -e

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
rc=0; reason=$("$DIR/applies.sh") || rc=$?
[ "$rc" -eq 1 ] && { echo "Skipping: $reason"; exit 0; }

echo "==> Writing NVIDIA modprobe config..."
CONF=/etc/modprobe.d/nvidia-graphics-drivers-kms.conf

# NVreg_DynamicPowerManagement=0x02 only works on Turing and newer.
# Read the chip codename from lspci, not nvidia-smi: in prime-select intel mode the
# driver isn't loaded and nvidia-smi only prints an error.
#   GK=Kepler GM=Maxwell GP=Pascal GV=Volta | TU=Turing GA=Ampere AD=Ada GB=Blackwell GH=Hopper
#   e.g. "GM107GLM [Quadro M2000M]" (Maxwell, no DPM), "GA107GLM [RTX A2000 Mobile]" (Ampere, DPM)
GPU_LINE=$(lspci -nn | grep -E 'VGA|3D|Display' | grep -i nvidia | head -1 | sed 's/.*NVIDIA Corporation //; s/ \[10de:.*//')
GPU_CHIP=$(echo "$GPU_LINE" | awk '{print $1}')
GPU_ARCH="$GPU_LINE"
SUPPORTS_DPM=false
case "$GPU_CHIP" in
    TU*|GA*|AD*|GB*|GH*) SUPPORTS_DPM=true ;;
esac

{
    echo "# /etc/modprobe.d/nvidia-graphics-drivers-kms.conf"
    echo "# Generated by ubuntu-fixes/fixes/nvidia-power/install.sh"
    echo "options nvidia_drm modeset=1"
    echo "options nvidia NVreg_PreserveVideoMemoryAllocations=1"
    echo "options nvidia NVreg_TemporaryFilePath=/var"
    if $SUPPORTS_DPM; then
        echo "options nvidia NVreg_DynamicPowerManagement=0x02"
        echo "==> GPU '$GPU_ARCH' supports dynamic power management — enabled." >&2
    else
        echo "==> GPU '$GPU_ARCH' does not support NVreg_DynamicPowerManagement, skipping." >&2
    fi
} > "$CONF"

echo "==> Switching to Intel prime mode..."
prime-select intel

echo "==> Updating initramfs..."
update-initramfs -u

echo "==> Done. Reboot required."
echo "    After reboot, verify with: cat /sys/bus/pci/devices/0000:01:00.0/power/runtime_status"
echo "    Expected: suspended"
